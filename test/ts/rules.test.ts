// Unit tests for sync-rules (src/sync/rules.ts): parsing, gitignore-style
// matching, rclone excludes per transferred path, the generated .gitignore
// section, the shipped defaults, and the private path guard reading them.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { HARNESS_ROOT } from '../../src/dev/image.ts';
import { DEFAULT_RULES, gitignoreSection, matchRule, parseRules, rcloneExcludes, readRules, writeGitignore } from '../../src/sync/rules.ts';
import { ENV, git, tmp, write } from './project.ts';

test('parseRules reads classes and patterns, skips comments, refuses malformed lines', () => {
  assert.deepEqual(parseRules('# c\nskip logs/\n\ndata *.db   # inline\nreview: plugins/X/PlayerData/\r\n'), [
    { cls: 'skip', pattern: 'logs/' },
    { cls: 'data', pattern: '*.db' },
    { cls: 'review', pattern: 'plugins/X/PlayerData/' },
  ]);
  assert.throws(() => parseRules('keep plugins/\n'), /sync-rules:1: expected "<skip\|data\|review> <pattern>", got "keep plugins\/"/);
  assert.throws(() => parseRules('data ../etc\n'), /can't use \.\. or !/);
  assert.throws(() => parseRules('skip !logs\n'), /can't use \.\. or !/);
});

test('matching is gitignore-style: anchored with a slash, any depth without, and everything below a match', () => {
  const rules = parseRules('skip plugins/ajLeaderboards/past-resets/\ndata *.db\ndata userdata/\nreview plugins/X/\n');
  const cases: [string, string | undefined][] = [
    ['plugins/ajLeaderboards/past-resets/2026-01-01.json', 'plugins/ajLeaderboards/past-resets/'],
    ['plugins/ajLeaderboards/config.yml', undefined],
    ['x/plugins/ajLeaderboards/past-resets/a.json', undefined],
    ['plugins/Eco/data.db', '*.db'],
    ['data.db', '*.db'],
    ['plugins/Essentials/userdata/steve.yml', 'userdata/'],
    ['plugins/X/config.yml', undefined],
  ];
  for (const [path, want] of cases) assert.equal(matchRule(rules, path)?.pattern, want, path);
  assert.equal(matchRule(rules, 'plugins/X/config.yml', ['review'])?.pattern, 'plugins/X/');
});

test('**/ and /**/ match zero or more directories; a pattern ending in / matches directories only', () => {
  const rules = parseRules('data plugins/**/x.db\ndata **/cache.json\ndata userdata/\nskip plugins/a/**\n');
  const cases: [string, string | undefined][] = [
    ['plugins/x.db', 'plugins/**/x.db'],
    ['plugins/A/x.db', 'plugins/**/x.db'],
    ['plugins/A/B/x.db', 'plugins/**/x.db'],
    ['plugins/B/y.db', undefined],
    ['cache.json', '**/cache.json'],
    ['plugins/C/cache.json', '**/cache.json'],
    ['plugins/E/userdata/u.yml', 'userdata/'],
    ['plugins/E/userdata', undefined],
    ['userdata', undefined],
    ['plugins/a/z.yml', 'plugins/a/**'],
  ];
  for (const [path, want] of cases) assert.equal(matchRule(rules, path)?.pattern, want, path);
  assert.equal(matchRule(rules, 'plugins/E/userdata', ['data'], true)?.pattern, 'userdata/');
});

test('rclone excludes are relative to the transferred path; anchored rules outside it drop out', () => {
  const rules = parseRules('skip plugins/ajLeaderboards/past-resets/\nskip logs/\ndata *.db\n');
  // Directory rules exclude what is below a directory of that name, not a file of it.
  assert.equal(rcloneExcludes(rules, ['skip', 'data']), '/plugins/ajLeaderboards/past-resets/**\nlogs/**\n*.db\n*.db/**\n');
  assert.equal(rcloneExcludes(rules, ['skip', 'data'], 'plugins'), '/ajLeaderboards/past-resets/**\nlogs/**\n*.db\n*.db/**\n');
  assert.equal(rcloneExcludes(rules, ['skip'], 'config'), 'logs/**\n');
  // A pull of a path a rule covers entirely transfers nothing.
  assert.equal(rcloneExcludes(rules, ['skip'], 'plugins/ajLeaderboards/past-resets/x'), '/**\nlogs/**\n');
  assert.equal(rcloneExcludes(rules, ['data'], 'plugins'), '*.db\n*.db/**\n');
});

test('the .gitignore section keeps skip and data paths under server/ out; rewriting it is idempotent', () => {
  const rules = parseRules('skip plugins/ajLeaderboards/past-resets/\ndata *.db\nreview plugins/X/\n');
  assert.equal(gitignoreSection(rules), '# >>> sync-rules: generated by bin/dev sync from sync-rules; edit that file\n/server/plugins/ajLeaderboards/past-resets/\n/server/**/*.db\n# <<< sync-rules');
  const dir = tmp();
  write(dir, { '.gitignore': '.env\n.dev/\n' });
  const f = join(dir, '.gitignore');
  assert.equal(writeGitignore(f, rules), true);
  assert.equal(writeGitignore(f, rules), false);
  assert.equal(writeGitignore(f, parseRules('data *.db\n')), true);
  assert.equal(readFileSync(f, 'utf8'), '.env\n.dev/\n# >>> sync-rules: generated by bin/dev sync from sync-rules; edit that file\n/server/**/*.db\n# <<< sync-rules\n');
  assert.match(gitignoreSection(parseRules('skip *.partial\nskip spark/tmp/\nskip: .trash/\n')), /\n\/server\/\*\*\/\*\.partial\n\/server\/spark\/tmp\/\n\/server\/\*\*\/\.trash\/\n/);
});

test('the shipped defaults parse, never sync past-resets and keep databases and player data out', () => {
  const rules = readRules(tmp());
  assert.deepEqual(rules, parseRules(readFileSync(DEFAULT_RULES, 'utf8')));
  assert.equal(matchRule(rules, 'plugins/ajLeaderboards/past-resets/x.json')?.cls, 'skip');
  for (const p of ['plugins/A/a.db', 'plugins/A/b.sqlite', 'plugins/A/c.mv.db', 'world/playerdata/u.dat', 'plugins/Essentials/userdata/u.yml']) assert.equal(matchRule(rules, p)?.cls, 'data', p);
  for (const p of ['logs/latest.log', 'plugins/x.partial', '.trash/a']) assert.equal(matchRule(rules, p)?.cls, 'skip', p);
  // Found by the first live sync: WorldEdit's unpacked jar, spark's temp files
  // under plugins/, SQLite's side files and archives.
  for (const p of ['plugins/WorldEdit/.archive-unpack/x/a.class', 'plugins/spark/tmp/p.tmp', 'plugins/Backup/2026-11-01.zip', 'w.zip']) assert.equal(matchRule(rules, p)?.cls, 'skip', p);
  for (const p of ['plugins/A/a.db-wal', 'plugins/A/a.db-shm']) assert.equal(matchRule(rules, p)?.cls, 'data', p);
  assert.equal(matchRule(rules, 'plugins/WorldEdit/config.yml'), undefined);
});

test('rule names match in any case, like the private guard', () => {
  const rules = readRules(tmp());
  for (const p of ['plugins/GriefPreventionData/PlayerData/u.yml', 'plugins/Eco/UserData/s.yml', 'plugins/A/Stats.DB', 'Logs/latest.log']) assert.ok(matchRule(rules, p), p);
  const anchored = parseRules('skip plugins/ajLeaderboards/past-resets/\n');
  assert.equal(matchRule(anchored, 'plugins/AJLeaderboards/Past-Resets/1.json')?.cls, 'skip');
});

test("the private path guard refuses server paths the repo's sync-rules mark skip or data", () => {
  const root = tmp();
  git(root, 'init', '-q', '-b', 'main');
  write(root, { 'sync-rules': 'data plugins/Eco/storage/\nskip spark/\n', 'server/plugins/Eco/storage/u.json': '{}', 'server/spark/x.txt': 'x', 'server/plugins/Eco/config.yml': 'a: 1\n' });
  git(root, 'add', '-A');
  const guard = (profile: string) => spawnSync(join(HARNESS_ROOT, 'bin/path-guard'), ['--staged', '--profile', profile], { cwd: root, env: ENV, encoding: 'utf8' });
  const r = guard('private');
  assert.equal(r.status, 2);
  assert.match(r.stderr, /server\/plugins\/Eco\/storage\/u\.json: sync-rules: data plugins\/Eco\/storage\//);
  assert.match(r.stderr, /server\/spark\/x\.txt: sync-rules: skip spark\//);
  assert.doesNotMatch(r.stderr, /config\.yml/);
  // Config, plugin configs and jars are what main tracks: the private guard lets them through.
  write(root, { 'sync-rules': 'data plugins/Eco/storage/\n' });
  git(root, 'rm', '-rq', '--cached', 'server');
  write(root, { 'server/server.properties': 'motd=x\n', 'server/plugins/Eco.jar': 'jar', 'server/purpur.jar': 'jar', 'server/bukkit.yml': 'a: 1\n' });
  git(root, 'add', 'server/server.properties', 'server/plugins/Eco.jar', 'server/purpur.jar', 'server/bukkit.yml', 'server/plugins/Eco/config.yml');
  const ok = guard('private');
  assert.equal(ok.status, 0, ok.stderr);
  write(root, { 'sync-rules': 'nonsense\n' });
  assert.match(guard('private').stderr, /sync-rules:1: expected/);
});

test("the template's .gitignore carries the section bin/dev sync generates from the default rules", () => {
  const dir = tmp();
  write(dir, { '.gitignore': readFileSync(join(HARNESS_ROOT, 'template', '.gitignore'), 'utf8') });
  assert.ok(readFileSync(join(dir, '.gitignore'), 'utf8').includes(gitignoreSection(readRules(tmp()))));
  assert.equal(writeGitignore(join(dir, '.gitignore'), readRules(tmp())), false);
});
