// sync-rules: one committed file in the private repo, read by every tool
// that moves or commits server files. Lines are `<class> <pattern>`, with
// gitignore-style patterns relative to the server root:
//   skip    never transferred, never committed
//   data    pulled only by bin/dev seed --with-data, never committed
//   review  proposed by bin/dev inventory; no effect until made skip or data
// A path no rule matches is synced and tracked. Defaults: templates/sync-rules.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fail } from '../dev/docker.ts';
import { HARNESS_ROOT } from '../dev/image.ts';

export type RuleClass = 'skip' | 'data' | 'review';
export type Rule = { cls: RuleClass; pattern: string };

export const DEFAULT_RULES = join(HARNESS_ROOT, 'templates', 'sync-rules');

export function parseRules(text: string, where = 'sync-rules'): Rule[] {
  const rules: Rule[] = [];
  text.split('\n').forEach((raw, i) => {
    const line = raw.replace(/\r$/, '').replace(/(^|\s)#.*$/, '').trim();
    if (line === '') return;
    const m = /^(skip|data|review):?\s+(\S+)$/.exec(line);
    if (!m) fail(`${where}:${i + 1}: expected "<skip|data|review> <pattern>", got "${line}"`);
    const pattern = m[2];
    if (pattern.split('/').includes('..') || pattern.startsWith('!')) fail(`${where}:${i + 1}: patterns can't use .. or ! (${pattern})`);
    rules.push({ cls: m[1] as RuleClass, pattern });
  });
  return rules;
}

// The project's sync-rules, else the harness defaults.
export function readRules(dir: string): Rule[] {
  const own = join(dir, 'sync-rules');
  const file = existsSync(own) ? own : DEFAULT_RULES;
  return parseRules(readFileSync(file, 'utf8'), file);
}

// gitignore globs: `**/` at the start and `/**/` inside match zero or more
// directories, any other `**` anything, `*` and `?` within one name.
const glob = (p: string) =>
  p
    .replace(/[.+^${}()|[\]\\]/g, '\\$&')
    .replace(/\/\*\*\//g, '/\x01')
    .replace(/^\*\*\//, '\x01')
    .replace(/\*\*/g, '\0')
    .replace(/\*/g, '[^/]*')
    .replace(/\?/g, '[^/]')
    .replace(/\x01/g, '(?:.*/)?')
    .replace(/\0/g, '.*');

// A pattern with a slash before its end is anchored at the server root;
// without one it matches a name at any depth. Either way it also matches
// everything below a matching directory.
// A pattern ending in / matches directories only: for a file path, only
// what lies below such a directory (`dir` says rel is a directory).
// Case is ignored, as the private guard ignores it: plugins name the same
// data PlayerData/ or playerdata/.
export function ruleRegex(pattern: string, dir = false): RegExp {
  const p = pattern.replace(/\/+$/, '');
  const anchored = p.includes('/');
  const body = glob(p.replace(/^\/+/, ''));
  const below = pattern.endsWith('/') && !dir ? '/.*' : '(/.*)?';
  return new RegExp(`${anchored ? '^' : '(^|/)'}${body}${below}$`, 'i');
}

// The first rule of the given classes matching a server-relative path.
export function matchRule(rules: Rule[], rel: string, classes: RuleClass[] = ['skip', 'data'], dir = false): Rule | undefined {
  return rules.find((r) => classes.includes(r.cls) && ruleRegex(r.pattern, dir).test(rel));
}

// An rclone exclude file (bin/mc MC_EXCLUDE_FILE) for the given classes, for
// a transfer of `base` (rclone matches relative to the path transferred):
// anchored rules are made relative to base, and dropped when outside it.
// {} and [] are rclone glob syntax but literal in rules: escaped.
export function rcloneExcludes(rules: Rule[], classes: RuleClass[], base = ''): string {
  const out: string[] = [];
  const b = base.replace(/^\/+|\/+$/g, '');
  for (const r of rules.filter((x) => classes.includes(x.cls))) {
    const p = r.pattern.replace(/\/+$/, '').replace(/^\/+/, '');
    let pat: string;
    if (!r.pattern.replace(/\/+$/, '').includes('/')) pat = p;
    else if (b === '') pat = `/${p}`;
    else if (p.startsWith(`${b}/`)) pat = `/${p.slice(b.length + 1)}`;
    else if (ruleRegex(r.pattern, true).test(b)) pat = '';
    else continue;
    pat = pat.replace(/[{}[\]]/g, '\\$&');
    // A directory-only rule leaves a file of that name alone.
    out.push(...(pat === '' ? ['/**'] : r.pattern.endsWith('/') ? [`${pat}/**`] : [pat, `${pat}/**`]));
  }
  return out.length ? `${out.join('\n')}\n` : '';
}

const BEGIN = '# >>> sync-rules: generated by bin/dev sync from sync-rules; edit that file';
const END = '# <<< sync-rules';

// The .gitignore section that keeps skip and data paths under server/ out of git.
export function gitignoreSection(rules: Rule[]): string {
  const lines = rules.filter((r) => r.cls !== 'review').map((r) => {
    const dir = r.pattern.endsWith('/') ? '/' : '';
    const p = r.pattern.replace(/\/+$/, '').replace(/^\/+/, '');
    return `${r.pattern.replace(/\/+$/, '').includes('/') ? `/server/${p}` : `/server/**/${p}`}${dir}`;
  });
  return [BEGIN, ...lines, END].join('\n');
}

// Write or replace the section in a .gitignore; returns whether it changed.
export function writeGitignore(file: string, rules: Rule[]): boolean {
  const old = existsSync(file) ? readFileSync(file, 'utf8') : '';
  const section = gitignoreSection(rules);
  const start = old.indexOf(BEGIN);
  const end = old.indexOf(END);
  const next = start >= 0 && end > start ? `${old.slice(0, start)}${section}${old.slice(end + END.length)}` : `${old}${old && !old.endsWith('\n') ? '\n' : ''}${section}\n`;
  if (next === old) return false;
  writeFileSync(file, next);
  return true;
}
